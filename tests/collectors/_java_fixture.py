def compile_class(source: str, class_name: str, *, tmp_path: Path) -> bytes:
    """Compiles `source` with the real `javac` and returns the resulting
    class file's bytes."""
    work_dir = tmp_path / f"javac-{class_name}"
    work_dir.mkdir(parents=True, exist_ok=True)
    source_path = work_dir / f"{class_name}.java"
    source_path.write_text(source)
    subprocess.run(["javac", str(source_path)], capture_output=True, check=True, cwd=work_dir)
    return (work_dir / f"{class_name}.class").read_bytes()


def build_jar(entries: dict[str, bytes], *, path: Path, compress: bool = True) -> Path:
    """Writes a real ZIP-format archive — which is all a JAR/WAR is."""
    mode = zipfile.ZIP_DEFLATED if compress else zipfile.ZIP_STORED
    with zipfile.ZipFile(path, "w", mode) as archive:
        for name, data in entries.items():
            archive.writestr(name, data)
    return path


