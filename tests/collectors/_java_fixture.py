"""Builds real Java artefacts for T-036a's tests: a genuinely compiled
`.class` file (via the system `javac`) packaged into a real JAR/WAR (via
`zipfile`, which is exactly what a JAR is).

A hand-crafted byte blob would not prove the constant-pool parser is
right — the parts most likely to be wrong (the `CONSTANT_Long`/
`CONSTANT_Double` two-slot rule, the real tag mix `javac` emits) only
show up in output from a real compiler."""

